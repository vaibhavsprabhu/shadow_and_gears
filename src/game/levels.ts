export interface LevelBlueprintData {
  players: PlayerActor[];
  guards: GuardActor[];
  walls: Rect[];
  zones: ZoneMarker[];
  bags: CashBag[];
  cars: TrafficCar[];
  rooftopGaps: RooftopGap[];
  highwayTarget: number;
  playerCarX: number;
  playerCarY: number;
}

function makePlayer(id: CrewId, x: number, y: number, hp = 100): PlayerActor {
  const c = CREW_ROSTER[id];
  return {
    id,
    name: c.name,
    role: c.role,
    x,
    y,
    angle: 0,
    speed: c.speed,
    radius: 13,
    color: c.color,
    carryingBag: false,
    hp,
    maxHp: hp,
    dashTimer: 0,
    dashCooldown: 0,
    hitFlash: 0,
    walkPhase: 0,
  };
}

